"""Unit tests for the classic email/password auth adapter (Phase 2 slice).

Spec: openspec/changes/phase2-classic-password/specs/phase2-classic-password/spec.md
- AS2.1: happy path — verify_password returns True for correct password
- AS2.2: wrong password — returns False (no leak)
- AS2.4: NULL password_hash — returns False (must use other auth flow)
- AS3.1: mint a reset token (returned and stored)
- AS4.1: consume the token — sets new hash, returns the user
- AS4.2: expired token — returns None
"""
from __future__ import annotations

